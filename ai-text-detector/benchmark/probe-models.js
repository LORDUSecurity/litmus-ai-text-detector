// Cheap model discovery probe: sends a handful of corpus texts to each candidate model
// and reports availability, parse success, and the scores. /v1/models lists models that
// 404/403 when called, so a real request is the only trustworthy test.
//
//   node probe-models.js                 # probe the built-in candidate list
//   node probe-models.js --per 4         # texts per model (2 AI + 2 HUMAN alternating)
//   node probe-models.js --only a,b      # restrict to specific model ids
//
// Never prints the API key.

const fs = require('fs');
const path = require('path');

function loadEnv(p) {
  const env = {};
  for (const line of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    if (line.trim().startsWith('#')) continue;
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return env;
}
const ENV = loadEnv(path.join(__dirname, '..', '.env'));

