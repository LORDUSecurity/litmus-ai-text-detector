// Same prompt as Build Primary Request in ai-only-workflow.json.
const SYSTEM = 'You are an AI text detection classifier. Return ONLY a compact JSON object. No markdown, no code fences, no commentary, no reasoning text. Schema: {"ai_probability": number between 0 and 1, "confidence": number between 0 and 1, "signals": up to 3 objects of {"name": string, "direction": "AI" or "HUMAN", "strength": number between 0 and 1}}. ai_probability means the probability the text was generated by an AI rather than written by a human. Keep the whole response under 180 tokens.';
const userPrompt = (t) => 'Was the following text likely written by an AI? Judge the text itself.\n\n"""\n' + t + '\n"""\n\nReturn ONLY the JSON object.';

// Defensive parse, mirroring the workflow's Parse Primary node.
function extract(payload) {
  if (payload && payload.error) {
    const e = payload.error;
    return { ok: false, code: String(e.code || e.status || 'provider_error'), detail: String(e.message || JSON.stringify(e)).slice(0, 140) };
  }
  const choice = (Array.isArray(payload && payload.choices) && payload.choices[0]) || null;
  if (!choice) return { ok: false, code: 'no_choices', detail: JSON.stringify(payload).slice(0, 140) };
  const msg = choice.message || {};
  let content = msg.content;
  if (content === null || content === undefined || content === '') content = msg.reasoning || '';
  if (typeof content !== 'string') { try { content = JSON.stringify(content); } catch (e) { content = ''; } }
  if (!content) return { ok: false, code: 'null_content', detail: 'message keys: ' + Object.keys(msg).join(',') };
  const stripped = content.replace(/```json/gi, '```').replace(/```/g, '').trim();
  const start = stripped.indexOf('{');
  if (start === -1) return { ok: false, code: 'no_json_object', detail: stripped.slice(0, 120) };
  let depth = 0, end = -1, inStr = false, esc = false;
  for (let i = start; i < stripped.length; i++) {
    const ch = stripped[i];
    if (inStr) { if (esc) esc = false; else if (ch === '\\') esc = true; else if (ch === '"') inStr = false; continue; }
    if (ch === '"') { inStr = true; continue; }
    if (ch === '{') depth++;
    else if (ch === '}') { depth--; if (depth === 0) { end = i; break; } }
  }
  const candidate = end > start ? stripped.slice(start, end + 1) : stripped.slice(start);
  let parsed = null;
  try { parsed = JSON.parse(candidate); } catch (e) {
    const ap = candidate.match(/"ai_probability"\s*:\s*(-?\d*\.?\d+)/);
    parsed = ap ? { ai_probability: parseFloat(ap[1]) } : null;
  }
  const p = parsed && parseFloat(parsed.ai_probability);
  if (!isFinite(p)) return { ok: false, code: 'missing_ai_probability', detail: candidate.slice(0, 120) };
  return { ok: true, p: Math.min(1, Math.max(0, p)), conf: Math.min(1, Math.max(0, parseFloat(parsed.confidence) || 0.5)) };
}

async function call(model, text) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 75000);
  const t0 = Date.now();
  try {
    const res = await fetch(ENV.PRIMARY_BASE_URL + '/chat/completions', {
      method: 'POST',
      headers: { Authorization: 'Bearer ' + ENV.PRIMARY_API_KEY, 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify({
        model, messages: [{ role: 'system', content: SYSTEM }, { role: 'user', content: userPrompt(text) }],
        temperature: 0.1, top_p: 0.9, max_tokens: 400, stream: false
      }),
      signal: ctrl.signal
    });
    const raw = await res.text();
    let payload;
    try { payload = JSON.parse(raw); } catch (e) { payload = { error: { code: res.status, message: raw.slice(0, 140) } }; }
    return { http: res.status, ms: Date.now() - t0, parsed: extract(payload), raw };
  } catch (e) {
    return { http: 0, ms: Date.now() - t0, parsed: { ok: false, code: 'exception', detail: String(e.message).slice(0, 120) } };
  } finally {
    clearTimeout(timer);
  }
}

async function pool(items, worker, n) {
  let next = 0;
  const run = async () => { while (true) { const i = next++; if (i >= items.length) return; await worker(items[i], i); } };
  await Promise.all(Array.from({ length: Math.min(n, items.length) }, run));
}

(async () => {
  const corpus = JSON.parse(fs.readFileSync(path.join(__dirname, 'corpus.json'), 'utf8'));
  // Take an even mix, one per domain where possible, so a model that only handles
  // one style of text does not look viable.
  const picks = [];
  for (const label of ['AI', 'HUMAN']) {
    const rows = corpus.filter((r) => r.label === label);
    const seen = new Set();
    for (const r of rows) {
      if (seen.has(r.config)) continue;
      seen.add(r.config);
      picks.push(r);
      if (picks.filter((x) => x.label === label).length >= PER / 2) break;
    }
  }
  const jobs = [];
  for (const m of CANDIDATES) for (const item of picks) jobs.push({ model: m, item });

  console.log('probing ' + CANDIDATES.length + ' models x ' + picks.length + ' texts = ' + jobs.length + ' calls');
  console.log('base_url=' + ENV.PRIMARY_BASE_URL + ' key=' + ENV.PRIMARY_API_KEY.slice(0, 7) + '...(len ' + ENV.PRIMARY_API_KEY.length + ')\n');

  const byModel = new Map();
  await pool(jobs, async ({ model, item }) => {
    if (!byModel.has(model)) byModel.set(model, []);
    const r = await call(model, item.text);
    byModel.get(model).push({ item, r });
    const tag = r.parsed.ok ? r.parsed.p.toFixed(2) : 'x';
    console.log('  ' + model.padEnd(46) + ' ' + item.id.padEnd(7) + ' ' + String(r.http).padEnd(4) + ' ' + String(r.ms).padStart(6) + 'ms  ' + tag);
  }, CONCURRENCY);

  console.log('\n================ SUMMARY ================');
  const rows = [];
  for (const [model, results] of byModel) {
    const ok = results.filter((x) => x.r.parsed.ok);
    const aiP = ok.filter((x) => x.item.label === 'AI').map((x) => x.r.parsed.p);
    const huP = ok.filter((x) => x.item.label === 'HUMAN').map((x) => x.r.parsed.p);
    const mean = (a) => (a.length ? a.reduce((s, v) => s + v, 0) / a.length : null);
    const sep = aiP.length && huP.length ? mean(aiP) - mean(huP) : null;
    const codes = [...new Set(results.filter((x) => !x.r.parsed.ok).map((x) => x.r.parsed.code + '/' + x.r.http))];
    rows.push({ model, ok: ok.length, total: results.length, ai: mean(aiP), hu: mean(huP), sep, ms: Math.max(...results.map((x) => x.r.ms)), codes });
  }
  rows.sort((a, b) => (b.sep === null ? -1 : b.sep) - (a.sep === null ? -1 : a.sep));
  console.log('model'.padEnd(46) + ' ok   AI_mean HUMAN_mean  sep   maxms  errors');
  for (const r of rows) {
    console.log(
      r.model.padEnd(46) +
      (r.ok + '/' + r.total).padEnd(6) +
      (r.ai === null ? '  -  ' : r.ai.toFixed(2).padStart(6)) +
      (r.hu === null ? '  -  ' : r.hu.toFixed(2).padStart(10)) +
      (r.sep === null ? '   -  ' : r.sep.toFixed(2).padStart(7)) +
      String(r.ms).padStart(7) + '  ' + r.codes.slice(0, 3).join(','));
  }
  console.log('\nmodels usable on every probe text: ' + rows.filter((r) => r.ok === r.total).length + '/' + rows.length);
})();
